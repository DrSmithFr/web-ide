// Milestones: one created from a ticket, its user stories written by Claude (MCP), the
// reminder in How to test, the milestone page validating its ticket To test, a feedback made
// into a ticket, then the milestone validated by the user once everything is done. Then the
// objectives: one given to a milestone, ordered, filtered, its page, reached by the user.
const { run, openProject, assert, mcp, OUT } = require('../common.cjs')

run(async ({ page }) => {
  page.on('dialog', (d) => d.accept())
  await openProject(page)
  await page.click('.rail-left .rail-btn[title="Kanban"]')
  await page.waitForSelector('[data-testid=kanban-panel]')
  await page.click('[data-testid=kanban-open-board]')
  await page.waitForSelector('[data-testid=kanban-board]')
  await mcp('kanban_create', { title: 'CSV export' })
  await mcp('kanban_set_plan', { id: 1, plan: 'Write the CSV', goals: [], size: 's', complexity: 'low' })
  await page.click('[data-testid=ticket-card-1]')
  await page.waitForSelector('[data-testid=ticket-view] [data-testid=ticket-status]:has-text("To do")')

  // A new milestone from the ticket.
  await page.selectOption('select[data-testid=ticket-milestone]', '-1')
  await page.waitForSelector('.modal input')
  await page.fill('.modal input', 'Exports')
  await page.keyboard.press('Enter')
  await page.waitForFunction(() => document.querySelector('select[data-testid=ticket-milestone]')?.value === '1')
  assert(true, 'a milestone created from the ticket, which joins it')
  await page.waitForSelector('[data-testid=card-milestone]:has-text("Exports")')
  assert(true, 'the card shows its milestone')

  // Claude writes a user story; the ticket To test recalls the milestone and its stories.
  const story = await mcp('kanban_milestone', { action: 'story_add', id: 1, text: 'As a user, I export my orders as CSV' })
  assert(story.result?.content?.[0]?.text.includes('User story added'), 'a user story written through the MCP endpoint')
  await page.click('.pane .tab:has-text("#1")')
  await page.click('[data-testid=ticket-start]')
  await page.waitForSelector('[data-testid=ticket-status]:has-text("In progress")')
  await page.click('[data-testid=ticket-to-test]')
  await page.waitForSelector('[data-testid=ticket-status]:has-text("To test")')
  await page.waitForSelector('[data-testid=ticket-milestone-reminder]:has-text("As a user, I export my orders as CSV")')
  assert((await page.textContent('[data-testid=ticket-milestone-reminder]')).includes('Exports'), 'How to test recalls the milestone and its user stories')
  // The progress bar of the milestone counts its tickets To test, in their color, after the finished ones.
  if (!(await page.isVisible('[data-testid=kanban-panel]'))) await page.click('.rail-left .rail-btn[title="Kanban"]')
  await page.click('[data-testid=kanban-open-milestones]')
  await page.waitForSelector('[data-testid=milestone-card-1] [data-testid=progress-bar] .ms-bar-totest')
  const bar = await page.$eval('[data-testid=milestone-card-1] [data-testid=progress-bar]', (e) => ({ title: e.title, width: e.querySelector('.ms-bar-totest').style.width }))
  assert(bar.width === '100%' && bar.title.includes('1 to test'), 'the bar of the milestone shows its ticket To test: ' + JSON.stringify(bar))
  await page.click('[data-testid=kanban-view-board]')
  await page.click('.pane .tab:has-text("#1")')

  // The milestone page: the ticket To test is validated there.
  await page.click('[data-testid=ticket-milestone-open]')
  await page.waitForSelector('[data-testid=milestone-view]')
  assert((await page.textContent('[data-testid=milestone-state]')).includes('Ongoing'), 'an open milestone is ongoing')
  assert(await page.isDisabled('[data-testid=milestone-validate]'), 'the milestone waits for its ticket and its story')
  assert((await page.textContent('[data-testid=milestone-coverage]')).includes('Opus'), 'Review coverage runs Claude Opus by default')
  await page.click('[data-testid=milestone-coverage]')
  await page.waitForFunction(() => [...document.querySelectorAll('.xterm-rows')].some((e) => e.textContent.includes('fake claude: --model opus /mcp__web-ide__coverage 1')))
  assert(true, 'Review coverage runs Claude Code on the milestone')
  await page.click('.pane .tab:has-text("Exports")')
  await page.waitForSelector('[data-testid=milestone-totest]:has-text("CSV export")')
  await page.click('[data-testid=milestone-ticket-close]')
  await page.waitForSelector('[data-testid=milestone-progress]:has-text("1/1")')
  assert(true, 'the ticket To test validated from the milestone page')

  // A feedback of the milestone made into a ticket of it.
  await page.selectOption('[data-testid=milestone-feedback-kind]', 'bug')
  await page.fill('[data-testid=milestone-feedback-input]', 'Dates are not ISO')
  await page.click('[data-testid=milestone-feedback-add]')
  await page.click('[data-testid=milestone-feedback-ticket]')
  await page.waitForSelector('[data-testid=milestone-feedback-link]:has-text("#2")')
  assert((await page.textContent('[data-testid=milestone-progress]')).includes('1/2'), 'the feedback became a ticket of the milestone')
  assert((await page.getAttribute('[data-testid=milestone-validate]', 'title')).includes('ticket'), 'validation waits for that ticket')

  // Everything done: the user validates the milestone.
  await page.click('[data-testid=milestone-feedback-link]')
  await page.waitForSelector('[data-testid=ticket-view] .tk-num:has-text("#2")')
  await page.click('.pane.active [data-testid=ticket-more]')
  await page.click('.ctx-menu button:has-text("Delete the ticket")')
  await page.click('.pane .tab:has-text("Exports")')
  await page.waitForSelector('[data-testid=milestone-progress]:has-text("1/1")')
  await page.click('[data-testid=milestone-feedback-check]')
  await page.click('[data-testid=milestone-story-check]')
  await page.waitForSelector('[data-testid=milestone-validate]:not([disabled])')
  await page.click('[data-testid=milestone-validate]')
  await page.waitForSelector('[data-testid=milestone-state]:has-text("Validated")')
  assert(await page.isVisible('[data-testid=milestone-reopen]'), 'the milestone validated by the user, then reopenable')
  const refused = await mcp('kanban_milestone', { action: 'validate', id: 1 })
  assert(refused.result?.isError, 'a model cannot validate a milestone')

  // A step shows the milestone of its root, chosen on the root.
  await mcp('kanban_create', { title: 'Root' })
  await mcp('kanban_create', { title: 'Its step', parent: 3 })
  await page.click('.pane .tab:has-text("Kanban")')
  await page.click('[data-testid=ticket-card-4]')
  await page.waitForSelector('[data-testid=ticket-view] button[data-testid=ticket-milestone]:has-text("#3")')
  await page.click('[data-testid=ticket-view] button[data-testid=ticket-milestone]')
  await page.waitForSelector('[data-testid=ticket-view] .tk-num:has-text("#3")')
  assert(await page.isVisible('select[data-testid=ticket-milestone]'), 'a step points to its root, where the milestone is chosen')

  // The board: a milestone filter, bands in the roadmap, the Milestones view.
  await mcp('kanban_milestone', { action: 'create', title: 'Imports' })
  await mcp('kanban_update', { id: 3, milestone: 2 })
  await mcp('kanban_create', { title: 'Other work' })
  await page.click('.pane .tab:has-text("Kanban")')
  await page.waitForSelector('[data-testid=kanban-board] [data-testid=ticket-card-5]')
  await page.selectOption('[data-testid=kanban-milestone-filter]', '2')
  await page.waitForSelector('[data-testid=kanban-board] [data-testid=ticket-card-5]', { state: 'detached' })
  assert(await page.isVisible('[data-testid=kanban-board] [data-testid=ticket-card-4]'), 'the filter keeps the tickets of the milestone (a step with its root)')
  await page.selectOption('[data-testid=kanban-milestone-filter]', 'all')
  await page.click('[data-testid=kanban-view-roadmap]')
  await page.waitForSelector('[data-testid=roadmap-band]:has-text("Imports")')
  assert((await page.$$eval('[data-testid=roadmap-band]', (l) => l.map((e) => e.textContent.trim()))).join() === 'Imports,No milestone', 'the roadmap groups the lineages of a milestone in a band')
  if (!(await page.isVisible('[data-testid=kanban-panel]'))) await page.click('.rail-left .rail-btn[title="Kanban"]')
  await page.click('[data-testid=kanban-open-milestones]')
  await page.waitForSelector('[data-testid=kanban-view-milestones][aria-pressed=true]')
  await page.waitForSelector('[data-testid=milestone-card-2]')
  await page.screenshot({ path: OUT + '/milestones-view.png' })
  assert((await page.textContent('[data-testid=milestone-card-2]')).includes('0/2'), 'the Milestones view shows the progress of each one')
  assert(!(await page.$('[data-testid=milestone-card-1]')), 'a validated milestone is folded')
  await page.click('[data-testid=milestone-card-2]')
  await page.waitForSelector('[data-testid=milestone-view] [data-testid=milestone-title]:has-text("Imports")')
  assert(true, 'a card opens its milestone')

  // Objectives: a new one as the default objective of a milestone, whose tickets follow.
  await page.selectOption('select[data-testid=milestone-objective]', '-1')
  await page.waitForSelector('.modal input')
  await page.fill('.modal input', 'MVP')
  await page.keyboard.press('Enter')
  await page.waitForFunction(() => document.querySelector('select[data-testid=milestone-objective]')?.value === '1')
  const step = await mcp('kanban_get', { id: 4 })
  assert(step.result?.content?.[0]?.text.includes('Objective 1 · MVP'), 'the default objective of a milestone reaches its tickets, a step with its root')
  await mcp('kanban_objective', { action: 'create', title: 'Launch', due: '2026-12-01' })
  await mcp('kanban_create', { title: 'Lone', objective: 2 })

  // The Milestones view: a section per objective, in their order, moved by the user.
  await page.click('.pane .tab:has-text("Kanban")')
  await page.click('[data-testid=kanban-view-milestones]')
  await page.waitForSelector('[data-testid=objective-section-2]')
  const order = () => page.$$eval('.ob-section[data-testid^=objective-section-]', (l) => l.map((e) => e.dataset.testid.replace('objective-section-', '')).join())
  assert((await order()) === '1,2', `objectives in their order: ${await order()}`)
  assert(await page.isVisible('[data-testid=objective-section-1] [data-testid=milestone-card-2]'), 'a milestone shows under its default objective')
  await page.click('[data-testid=objective-section-2] [data-testid=objective-up]')
  await page.waitForFunction(() => document.querySelector('.ob-section')?.dataset.testid === 'objective-section-2')
  assert(true, 'an objective moved up')
  await page.screenshot({ path: OUT + '/objectives-view.png' })

  // The board: the objective filter and the badge of a card.
  await page.click('[data-testid=kanban-view-board]')
  await page.selectOption('[data-testid=kanban-objective-filter]', '2')
  await page.waitForSelector('[data-testid=kanban-board] [data-testid=ticket-card-5]', { state: 'detached' })
  assert((await page.textContent('[data-testid=ticket-card-6] [data-testid=card-objective]')).includes('Launch'), 'the filter keeps the tickets of the objective, the card shows it')
  await page.selectOption('[data-testid=kanban-objective-filter]', 'all')

  // A lone ticket put in an objective; the objective page groups its tickets by milestone.
  await page.click('[data-testid=ticket-card-5]')
  await page.waitForSelector('[data-testid=ticket-view] [data-testid=ticket-title]:has-text("Other work")')
  await page.selectOption('select[data-testid=ticket-objective]', '1')
  await page.waitForSelector('[data-testid=ticket-objective-open]')
  await page.click('[data-testid=ticket-objective-open]')
  await page.waitForSelector('[data-testid=objective-view] [data-testid=objective-title]:has-text("MVP")')
  await page.waitForSelector('[data-testid=objective-progress]:has-text("0/3")')
  assert((await page.$$eval('[data-testid=objective-group] .kb-panel-group', (l) => l.map((e) => e.textContent.trim()))).join('|') === 'Imports0/2|No milestone0/1', 'the tickets of the objective, by milestone then lone')
  assert(await page.isDisabled('[data-testid=objective-reach]'), 'an objective waits for its tickets')

  // Reached by the user once its tickets are finished.
  await page.goto(page.url().replace(/[?#].*$/, '') + '?ticket=6')
  await page.waitForSelector('[data-testid=ticket-view] [data-testid=ticket-title]:has-text("Lone")')
  await page.click('[data-testid=ticket-more]')
  await page.click('.ctx-menu button:has-text("Change the status…")')
  await page.waitForSelector('.pick-input')
  await page.keyboard.type('Done')
  await page.keyboard.press('Enter')
  await page.fill('.modal-small input', '')
  await page.keyboard.press('Enter')
  await page.waitForSelector('[data-testid=ticket-status]:has-text("Done")')
  await page.goto(page.url().replace(/[?#].*$/, '') + '?objective=2')
  await page.waitForSelector('[data-testid=objective-view] [data-testid=objective-due]:has-text("2026")')
  await page.click('[data-testid=objective-reach]')
  await page.waitForSelector('[data-testid=objective-state]:has-text("Reached")')
  assert(await page.isVisible('[data-testid=objective-reopen]'), 'the objective reached by the user, then reopenable')
})
